let current: IconPack = "line";

export function isIconPack(v: unknown): v is IconPack {
  return ICON_PACKS.some((p) => p.id === v);
}

const pixelCache = new Map<string, string>();
function pixelSvg(name: string): string | null {
  const art = PIXEL[name];
  if (!art) return null;
  let svg = pixelCache.get(name);
  if (!svg) {
    let full = "";
    let half = "";
    art.split("/").forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        // One run of pixels per segment: fewer path commands.
        const ch = row[x];
        if (ch !== "#" && ch !== "+") continue;
        let end = x;
        while (row[end + 1] === ch) end++;
        const seg = `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
        if (ch === "#") full += seg;
        else half += seg;
        x = end;
      }
    });
    svg = `<svg viewBox="0 0 12 12" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true"><path d="${full}"/>${half ? `<path d="${half}" fill-opacity=".38"/>` : ""}</svg>`;
    pixelCache.set(name, svg);
  }
  return svg;
}

/** The SVG of an icon in a pack (the current one by default). */
export function iconSvg(name: string, pack: IconPack = current): string {
  if (pack === "pixel") {
    const px = pixelSvg(name);
    if (px) return px;
  }
  let body = LINE[name] ?? "";
  if (pack === "duotone") body = body.replace(/class="f"/g, 'class="f" fill="currentColor" fill-opacity=".2"');
  const width = pack === "bold" ? 2.3 : 1.7;
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

/** An icon; with `pack`, it keeps that pack (previews in the settings). */
export function icon(name: string, cls = "", pack?: IconPack): HTMLSpanElement {
  const span = document.createElement("span");
  span.className = `kn-icon ${cls}`.trim();
  span.dataset.i = name;
  if (pack) span.dataset.pack = pack;
  // Static, home-made markup (never user input).
  span.innerHTML = iconSvg(name, pack ?? current);
  return span;
}

/** Switches the pack: every icon on screen is redrawn. */
export function setIconPack(pack: IconPack) {
  document.documentElement.dataset.icons = pack;
  if (pack === current) return;
  current = pack;
  document.querySelectorAll<HTMLElement>(".kn-icon[data-i]:not([data-pack])").forEach((el) => {
    el.innerHTML = iconSvg(el.dataset.i!, pack);
  });
}
