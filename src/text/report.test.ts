import { describe, expect, it } from "vitest";
import { DEFAULT_SETTINGS } from "../core/settings";
import { makeTaskConfig } from "./tasks";
import { buildReport, periodFor } from "./report";

const cfg = makeTaskConfig({
  statuses: DEFAULT_SETTINGS.task_statuses,
  cycle: DEFAULT_SETTINGS.task_cycle,
  done: DEFAULT_SETTINGS.task_done_statuses,
  archiveStatus: "done",
  archiveDate: true,
});
const today = new Date(2026, 10, 2);

describe("activity report", () => {
  const sources = [
    {
      project: "work",
      doneText: [
        "- call colleague X - done [2026-01-15]",
        "- migrate the database - ok [2026-01-20]",
        "- old thing - done [2025-06-01]",
        "- undated task - ok",
        "",
        "# ignored heading",
      ].join("\n"),
      activeText: "- API spec - ongoing\n- demo - todo\n- bug - blocked\n- finished - done",
    },
    { project: "personal", doneText: "- read a book - done [2026-03-03]", activeText: null },
  ];

  it("filters on the year and groups by project and by month", () => {
    const md = buildReport(sources, cfg, periodFor("year", today), today);
    expect(md).toContain("# Activity report — Year 2026");
    expect(md).toContain("_Generated by KiloNote on November 2, 2026._");
    expect(md).toContain("**3 tasks completed** across **2 projects**");
    expect(md).toContain("| work | 2 | 1 | 1 | 1 |");
    expect(md).toContain("### January 2026\n- call colleague X\n- migrate the database");
    // Undated tasks cannot be placed in a period: only "All time" counts them.
    expect(md).not.toContain("undated task");
    expect(md).toContain("_1 archived task has no date: only “All time” counts it._");
    expect(md).not.toContain("old thing");
    expect(md).toContain("Most productive month: **January 2026** (2 tasks)");
    expect(md).toContain("- **work**: API spec");
  });

  it("covers the previous year", () => {
    const md = buildReport(sources, cfg, periodFor("lastYear", today), today);
    expect(md).toContain("- old thing");
    expect(md).not.toContain("call colleague X");
  });

  it("all time includes the undated tasks", () => {
    const md = buildReport(sources, cfg, periodFor("all", today), today);
    expect(md).toContain("### Undated\n- undated task");
    expect(md).toContain("| work | 4 |");
  });

  it("weeks start on Monday, months are calendar months", () => {
    const wed = new Date(2026, 10, 4);
    expect(periodFor("week", wed)).toMatchObject({ from: "2026-11-02", to: "2026-11-08", label: "Week of Nov 2, 2026" });
    expect(periodFor("lastWeek", wed)).toMatchObject({ from: "2026-10-26", to: "2026-11-01" });
    expect(periodFor("month", wed)).toMatchObject({ from: "2026-11-01", to: "2026-11-30", label: "November 2026" });
    expect(periodFor("lastMonth", new Date(2026, 0, 15))).toMatchObject({ from: "2025-12-01", to: "2025-12-31" });
    expect(periodFor("week", new Date(2026, 10, 8))).toMatchObject({ from: "2026-11-02", to: "2026-11-08" });
  });

  it("can be limited to a tag", () => {
    const tagged = [
      { project: "work", doneText: "- fix login #client - done [2026-02-01]\n- refactor - done [2026-02-02]", activeText: "- demo #Client - ongoing\n- other - todo" },
    ];
    const md = buildReport(tagged, cfg, periodFor("year", today), today, { tag: "#client" });
    expect(md).toContain("# Activity report — Year 2026 · #client");
    expect(md).toContain("- fix login #client");
    expect(md).not.toContain("refactor");
    expect(md).toContain("| work | 1 | 1 | 0 | 0 |");
  });

  it("uses the configured ongoing and blocked statuses", () => {
    const custom = makeTaskConfig({
      statuses: { todo: "blue", wip: "orange", stuck: "red", done: "green" },
      cycle: ["todo", "wip", "done"], done: ["done"], ongoing: ["wip"], blocked: ["stuck"], archiveStatus: "done", archiveDate: true,
    });
    const md = buildReport([{ project: "p", doneText: "- a - done [2026-01-01]", activeText: "- b - wip\n- c - stuck\n- d - todo" }], custom, periodFor("year", today), today);
    expect(md).toContain("| p | 1 | 1 | 1 | 1 |");
    expect(md).toContain("- **p**: b");
  });

  it("shows a hint when there is nothing to report", () => {
    expect(buildReport([], cfg, periodFor("all", today), today)).toContain("No archived task found");
  });
});
