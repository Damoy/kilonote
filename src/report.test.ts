import { describe, expect, it } from "vitest";
import { DEFAULT_SETTINGS } from "./core/settings";
import { makeTaskConfig } from "./editor/tasks";
import { buildReport, periodFor } from "./report";

const cfg = makeTaskConfig({
  statuses: DEFAULT_SETTINGS.task_statuses,
  cycle: DEFAULT_SETTINGS.task_cycle,
  done: DEFAULT_SETTINGS.task_done_statuses,
  archiveStatus: "done",
  archiveDate: true,
});
const today = new Date(2026, 10, 2);

describe("activity report", () => {
  const sources = [
    {
      project: "work",
      doneText: [
        "- call colleague X - done [2026-01-15]",
        "- migrate the database - ok [2026-01-20]",
        "- old thing - done [2025-06-01]",
        "- undated task - ok",
        "",
        "# ignored heading",
      ].join("\n"),
      activeText: "- API spec - ongoing\n- demo - todo\n- bug - blocked\n- finished - done",
    },
    { project: "personal", doneText: "- read a book - done [2026-03-03]", activeText: null },
  ];

  it("filters on the year and groups by project and by month", () => {
    const md = buildReport(sources, cfg, periodFor("year", today), today);
    expect(md).toContain("# Activity report — Year 2026");
    expect(md).toContain("_Generated by KiloNote on November 2, 2026._");
    expect(md).toContain("**4 tasks completed** across **2 projects**");
    expect(md).toContain("| work | 3 | 1 | 1 | 1 |");
    expect(md).toContain("### January 2026\n- call colleague X\n- migrate the database");
    expect(md).toContain("### Undated\n- undated task");
    expect(md).not.toContain("old thing");
    expect(md).toContain("Most productive month: **January 2026** (2 tasks)");
    expect(md).toContain("- **work**: API spec");
  });

  it("covers the previous year", () => {
    const md = buildReport(sources, cfg, periodFor("lastYear", today), today);
    expect(md).toContain("- old thing");
    expect(md).not.toContain("call colleague X");
  });

  it("shows a hint when there is nothing to report", () => {
    expect(buildReport([], cfg, periodFor("all", today), today)).toContain("No archived task found");
  });
});
